def set_lang(choice: str) -> str:
    """choice: 'auto' | 'ru' | 'en'. Возвращает применённый язык."""
    global _lang
    if choice not in ("ru", "en"):
        choice = "ru" if au.system_language().lower().startswith("ru") else "en"
    _lang = choice
    return _lang


def current() -> str:
    return _lang


def tr(key: str, **kw) -> str:
    text = STRINGS.get(_lang, {}).get(key) or STRINGS["ru"].get(key) or key
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError):
            return text
    return text
